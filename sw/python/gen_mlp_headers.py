#!/usr/bin/env python3
"""
Generate the C headers the MLP bare-metal app needs:

  mlp_weights.h     6 const u8 arrays (L1..L3 weights + biases), raw bytes
  mlp_test_image.h  one 784-pixel test image + golden logits + golden pred

The golden values come from a bit-exact Python model of rtl/mlp_layer.v:
  acc  = sum(int8 act * int8 weight)      (32-bit signed)
  acc  = acc >>> SHIFT_AMT                (arithmetic shift)
  acc += int8 bias
  relu (layers 1, 2 only)
  saturate to [-128, 127]

Usage:
  python3 gen_mlp_headers.py --repo /path/to/Project_2 --out ../mlp
"""
import argparse
import os
import sys

N_IN, N_H1, N_H2, N_OUT = 784, 256, 128, 10

# per-layer settings, must match the mlp_layer instantiations in mlp_top.v
LAYERS = [
    # (n_inputs, n_neurons, shift, relu)
    (N_IN, N_H1, 7, True),
    (N_H1, N_H2, 7, True),
    (N_H2, N_OUT, 9, False),
]


def read_hex_bytes(path, expected_len):
    """One byte per line, two hex digits. Returns a list of ints 0..255."""
    with open(path) as f:
        vals = [int(line.strip(), 16) & 0xFF for line in f if line.strip()]
    if len(vals) != expected_len:
        sys.exit(f"{path}: expected {expected_len} bytes, found {len(vals)}")
    return vals


def to_s8(b):
    return b - 256 if b >= 128 else b


def mlp_layer(act, w, b, n_in, n_out, shift, relu):
    """Bit-exact model of one mlp_layer instance. act/w/b are signed ints."""
    out = []
    for n in range(n_out):
        base = n * n_in
        acc = 0
        for i in range(n_in):
            acc += act[i] * w[base + i]
        acc >>= shift                      # Python >> on ints is arithmetic
        acc += b[n]
        if relu and acc < 0:
            acc = 0
        acc = max(-128, min(127, acc))
        out.append(acc)
    return out


def c_array(name, ctype, values, per_line=16):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        if ctype == "s8":
            lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
        else:
            lines.append("    " + ", ".join(f"0x{v:02X}" for v in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="path to the Project_2 repo")
    ap.add_argument("--out", default=".", help="output directory for headers")
    ap.add_argument("--image", default="mnist_89_q17.hex",
                    help="image hex file, relative to --repo")
    args = ap.parse_args()

    wdir = os.path.join(args.repo, "weights")
    files = {
        "l1_w": ("layer1_weights.hex", N_IN * N_H1),
        "l1_b": ("layer1_bias.hex",    N_H1),
        "l2_w": ("layer2_weights.hex", N_H1 * N_H2),
        "l2_b": ("layer2_bias.hex",    N_H2),
        "l3_w": ("layer3_weights.hex", N_H2 * N_OUT),
        "l3_b": ("layer3_bias.hex",    N_OUT),
    }
    raw = {k: read_hex_bytes(os.path.join(wdir, fn), n) for k, (fn, n) in files.items()}
    img = read_hex_bytes(os.path.join(args.repo, args.image), N_IN)

    # ---- golden model ----
    s = {k: [to_s8(v) for v in raw[k]] for k in raw}
    act = [to_s8(v) for v in img]
    params = [("l1_w", "l1_b"), ("l2_w", "l2_b"), ("l3_w", "l3_b")]
    for (wk, bk), (n_in, n_out, shift, relu) in zip(params, LAYERS):
        act = mlp_layer(act, s[wk], s[bk], n_in, n_out, shift, relu)
    logits = act
    pred = max(range(N_OUT), key=lambda k: (logits[k], -k))   # first index wins a tie

    print("golden logits:", logits)
    print("golden pred  :", pred)

    # ---- write headers ----
    os.makedirs(args.out, exist_ok=True)

    with open(os.path.join(args.out, "mlp_weights.h"), "w") as f:
        f.write("/* GENERATED by gen_mlp_headers.py, do not edit. */\n")
        f.write("/* Include from exactly one .c file (main.c). */\n")
        f.write("#ifndef MLP_WEIGHTS_H\n#define MLP_WEIGHTS_H\n\n")
        f.write('#include "xil_types.h"\n\n')
        for k in files:
            f.write(c_array(f"{k}_data", "u8", raw[k]) + "\n\n")
        f.write("#endif\n")

    with open(os.path.join(args.out, "mlp_test_image.h"), "w") as f:
        f.write("/* GENERATED by gen_mlp_headers.py, do not edit. */\n")
        f.write(f"/* image: {args.image} */\n")
        f.write("#ifndef MLP_TEST_IMAGE_H\n#define MLP_TEST_IMAGE_H\n\n")
        f.write('#include "xil_types.h"\n\n')
        f.write(c_array("test_pixels", "u8", img) + "\n\n")
        f.write(c_array("test_expected_logits", "s8", logits) + "\n\n")
        f.write(f"#define TEST_EXPECTED_PRED  {pred}u\n\n")
        f.write("#endif\n")

    print(f"wrote mlp_weights.h and mlp_test_image.h to {os.path.abspath(args.out)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""
Generate the C headers the SNN bare-metal app needs:

  snn_weights.h      3 const u8 arrays (L1..L3 weights), raw bytes
  snn_test_spikes.h  25 timesteps x 784 input spikes (0/1)
                     + golden class counts, pred, skipped-MAC count

The golden values come from a bit-exact Python model of rtl/lif_layer.v.
Per timestep, per neuron:
  acc = (mem * BETA) >>> 8                     decay once (BETA = 243)
  for each input i: if spike[i]: acc += w << 1 (Q1.7 -> Q8.8)
                    else:        skipped += 1
  spike_out = acc >= THRESHOLD (256)
  mem = 0 if spike_out else acc
Class count k = number of timesteps where output neuron k spiked.

Usage:
  python3 gen_snn_headers.py --repo /path/to/Project_2 --out ../snn
"""
import argparse
import os
import sys

N_IN, N_H1, N_H2, N_OUT = 784, 256, 128, 10
T = 25
BETA = 243
THRESHOLD = 256


def read_hex_bytes(path, expected_len):
    with open(path) as f:
        vals = [int(line.strip(), 16) & 0xFF for line in f if line.strip()]
    if len(vals) != expected_len:
        sys.exit(f"{path}: expected {expected_len} bytes, found {len(vals)}")
    return vals


def read_spikes(path):
    with open(path) as f:
        vals = [int(float(line.strip())) for line in f if line.strip()]
    if len(vals) != N_IN or any(v not in (0, 1) for v in vals):
        sys.exit(f"{path}: expected {N_IN} lines of 0/1")
    return vals


def to_s8(b):
    return b - 256 if b >= 128 else b


def lif_layer(spk_in, w, mem, n_in, n_out):
    """Bit-exact model of one lif_layer timestep. Updates mem in place."""
    out = []
    skipped = 0
    active = [i for i in range(n_in) if spk_in[i]]
    skipped = (n_in - len(active)) * n_out
    for n in range(n_out):
        acc = (mem[n] * BETA) >> 8           # arithmetic shift, matches >>>
        base = n * n_in
        for i in active:
            acc += w[base + i] << 1
        fired = 1 if acc >= THRESHOLD else 0
        mem[n] = 0 if fired else acc
        out.append(fired)
    return out, skipped


def c_array(name, ctype, values, per_line=16, hexfmt=True):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        if hexfmt:
            lines.append("    " + ", ".join(f"0x{v:02X}" for v in chunk) + ",")
        else:
            lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="path to the Project_2 repo")
    ap.add_argument("--out", default=".", help="output directory for headers")
    args = ap.parse_args()

    wdir = os.path.join(args.repo, "data_layer", "weights")
    files = {
        "l1_w": ("weights_layer1.hex", N_IN * N_H1),
        "l2_w": ("weights_layer2.hex", N_H1 * N_H2),
        "l3_w": ("weights_layer3.hex", N_H2 * N_OUT),
    }
    raw = {k: read_hex_bytes(os.path.join(wdir, fn), n) for k, (fn, n) in files.items()}
    spikes = [read_spikes(os.path.join(args.repo, "spike", f"spikes_t{t}.txt"))
              for t in range(T)]

    # ---- golden model ----
    w1 = [to_s8(v) for v in raw["l1_w"]]
    w2 = [to_s8(v) for v in raw["l2_w"]]
    w3 = [to_s8(v) for v in raw["l3_w"]]
    m1, m2, m3 = [0] * N_H1, [0] * N_H2, [0] * N_OUT
    counts = [0] * N_OUT
    skipped_total = 0
    for t in range(T):
        s1, k1 = lif_layer(spikes[t], w1, m1, N_IN, N_H1)
        s2, k2 = lif_layer(s1, w2, m2, N_H1, N_H2)
        s3, k3 = lif_layer(s2, w3, m3, N_H2, N_OUT)
        skipped_total += k1 + k2 + k3
        for k in range(N_OUT):
            counts[k] += s3[k]
        print(f"t={t:2d}  L1 spikes={sum(s1):3d}  L2={sum(s2):3d}  out={s3}")
    pred = max(range(N_OUT), key=lambda k: (counts[k], -k))   # first index wins a tie

    print("golden class counts:", counts)
    print("golden pred        :", pred)
    print("golden skipped MACs:", skipped_total)

    # ---- write headers ----
    os.makedirs(args.out, exist_ok=True)

    with open(os.path.join(args.out, "snn_weights.h"), "w") as f:
        f.write("/* GENERATED by gen_snn_headers.py, do not edit. */\n")
        f.write("/* Include from exactly one .c file (main.c). */\n")
        f.write("#ifndef SNN_WEIGHTS_H\n#define SNN_WEIGHTS_H\n\n")
        f.write('#include "xil_types.h"\n\n')
        for k in files:
            f.write(c_array(f"{k}_data", "u8", raw[k]) + "\n\n")
        f.write("#endif\n")

    with open(os.path.join(args.out, "snn_test_spikes.h"), "w") as f:
        f.write("/* GENERATED by gen_snn_headers.py, do not edit. */\n")
        f.write("#ifndef SNN_TEST_SPIKES_H\n#define SNN_TEST_SPIKES_H\n\n")
        f.write('#include "xil_types.h"\n\n')
        f.write(f"/* test_spikes[t][i]: input spike i at timestep t, 0 or 1 */\n")
        f.write(f"static const u8 test_spikes[{T}][{N_IN}] = {{\n")
        for t in range(T):
            f.write("    {")
            f.write(",".join(str(v) for v in spikes[t]))
            f.write("},\n")
        f.write("};\n\n")
        f.write(c_array("test_expected_counts", "u8", counts, hexfmt=False) + "\n\n")
        f.write(f"#define TEST_EXPECTED_PRED     {pred}u\n")
        f.write(f"#define TEST_EXPECTED_SKIPPED  {skipped_total}u\n\n")
        f.write("#endif\n")

    print(f"wrote snn_weights.h and snn_test_spikes.h to {os.path.abspath(args.out)}")


if __name__ == "__main__":
    main()
